using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace PKHeX.Everywhere.Engine.Generators;

[Generator]
public sealed class HandlerGenerator : IIncrementalGenerator
{
    private const string QueryAttribute = "PKHeX.Everywhere.Engine.QueryAttribute";
    private const string CommandAttribute = "PKHeX.Everywhere.Engine.CommandAttribute";
    private const string HandleInterface = "PKHeX.Everywhere.Engine.IHandle";

    private static readonly DiagnosticDescriptor NotStatic = new(
        "PKE001", "Handler must be static", "Handler '{0}' must be a static method", "Engine", DiagnosticSeverity.Error, true);

    private static readonly DiagnosticDescriptor DuplicateCall = new(
        "PKE002", "Duplicate call name", "Call '{0}' is declared more than once", "Engine", DiagnosticSeverity.Error, true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var queries = Handlers(context, QueryAttribute);
        var commands = Handlers(context, CommandAttribute);
        var ns = context.CompilationProvider.Select(static (compilation, _) => Namespace(compilation.AssemblyName));

        context.RegisterSourceOutput(queries.Combine(commands).Combine(ns),
            static (spc, input) => Emit(spc, input.Right, input.Left.Left.AddRange(input.Left.Right)));
    }

    private static IncrementalValueProvider<ImmutableArray<IMethodSymbol>> Handlers(IncrementalGeneratorInitializationContext context, string attribute) =>
        context.SyntaxProvider.ForAttributeWithMetadataName(
            attribute,
            static (node, _) => node is MethodDeclarationSyntax,
            static (ctx, _) => (IMethodSymbol)ctx.TargetSymbol).Collect();

    // Each assembly gets its own registry in its own namespace, so the Engine's internal one never clashes with it.
    private static string Namespace(string? assemblyName) => string.Join(".", (assemblyName ?? "Handlers")
        .Split('.')
        .Select(segment => new string(segment.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray()))
        .Select(segment => segment.Length == 0 || char.IsDigit(segment[0]) ? "_" + segment : segment));

    private static void Emit(SourceProductionContext context, string ns, ImmutableArray<IMethodSymbol> methods)
    {
        var json = new JsonEmitter(context);
        var cases = new StringBuilder();
        var names = new List<string>();

        foreach (var method in methods.OrderBy(m => CallName(m)))
        {
            var location = method.Locations.FirstOrDefault();
            var name = CallName(method);

            if (!method.IsStatic)
            {
                context.ReportDiagnostic(Diagnostic.Create(NotStatic, location, method.Name));
                continue;
            }

            if (names.Contains(name))
            {
                context.ReportDiagnostic(Diagnostic.Create(DuplicateCall, location, name));
                continue;
            }

            names.Add(name);
            cases.Append(EmitCase(json, method, name, location));
        }

        var registry = $$"""
            // <auto-generated />
            #nullable disable
            using System.Text.Json;

            namespace {{ns}};

            internal static class HandlerRegistry
            {
                public static bool TryInvoke(global::PKHeX.Everywhere.Engine.Session session, string call, JsonElement args, Utf8JsonWriter writer)
                {
                    switch (call)
                    {
            {{cases}}        }

                    return false;
                }

                private static void ExpectArgs(string call, JsonElement args, int count)
                {
                    if (args.GetArrayLength() != count)
                        throw new global::PKHeX.Everywhere.Engine.EngineException(global::PKHeX.Everywhere.Engine.ErrorCodes.BadArguments, $"'{call}' takes {count} argument(s), got {args.GetArrayLength()}.");
                }

                private static T Arg<T>(string name, System.Func<T> read)
                {
                    try
                    {
                        return read();
                    }
                    catch (System.Exception e) when (e is not global::PKHeX.Everywhere.Engine.EngineException)
                    {
                        throw new global::PKHeX.Everywhere.Engine.EngineException(global::PKHeX.Everywhere.Engine.ErrorCodes.BadArguments, $"Invalid argument '{name}': {e.Message}", e);
                    }
                }
            }
            """;

        context.AddSource("HandlerRegistry.g.cs", registry);
        context.AddSource("GeneratedJson.g.cs", json.Build(ns));
    }

    private static AttributeData HandlerAttribute(IMethodSymbol method) =>
        method.GetAttributes().First(a => a.AttributeClass?.ToDisplayString() is QueryAttribute or CommandAttribute);

    private static string CallName(IMethodSymbol method) => HandlerAttribute(method).ConstructorArguments[0].Value as string ?? "";

    private static bool IsCommand(IMethodSymbol method) => HandlerAttribute(method).AttributeClass?.ToDisplayString() == CommandAttribute;

    private static IEnumerable<string> DeclaredTopics(IMethodSymbol method) =>
        HandlerAttribute(method).ConstructorArguments[1].Values.Select(v => $"\"{v.Value}\"");

    private static bool IsHandle(ITypeSymbol type) =>
        type.AllInterfaces.Any(i => i.ToDisplayString() == HandleInterface);

    private static string EmitCase(JsonEmitter json, IMethodSymbol method, string name, Location? location)
    {
        var sb = new StringBuilder();
        var arguments = new List<string>();
        var written = new List<string>();
        var mayWriteNothing = false;
        var jsonIndex = 0;

        sb.AppendLine($"            case \"{name}\":");
        sb.AppendLine("            {");

        var jsonParameters = method.Parameters.Where(p => Injected(p.Type) is null).ToList();
        sb.AppendLine($"                ExpectArgs(call, args, {jsonParameters.Count});");

        foreach (var parameter in method.Parameters)
        {
            var type = parameter.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            if (Injected(parameter.Type) is { } injected)
            {
                sb.AppendLine($"                var i{arguments.Count} = {injected};");
                arguments.Add($"i{arguments.Count}");
                continue;
            }

            var read = json.Read(parameter.Type, $"args[{jsonIndex}]", location);
            sb.AppendLine($"                var a{jsonIndex} = Arg<{type}>(\"{parameter.Name}\", () => {read});");
            arguments.Add($"a{jsonIndex}");
            if (IsHandle(parameter.Type))
            {
                var nullable = parameter.Type.NullableAnnotation == NullableAnnotation.Annotated;
                mayWriteNothing |= nullable;
                written.Add(nullable ? $"a{jsonIndex}?.Topic()" : $"a{jsonIndex}.Topic()");
            }
            jsonIndex++;
        }

        var invocation = $"{method.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}.{method.Name}({string.Join(", ", arguments)})";

        if (IsCommand(method))
        {
            var topics = $"new string[] {{ {string.Join(", ", written.Concat(DeclaredTopics(method)))} }}";
            if (mayWriteNothing)
                topics = $"global::System.Linq.Enumerable.ToArray(global::System.Linq.Enumerable.OfType<string>({topics}))";
            invocation = method.ReturnsVoid
                ? $"session.RunCommand({topics}, () => {{ {invocation}; return true; }})"
                : $"session.RunCommand({topics}, () => {invocation})";
        }

        if (method.ReturnsVoid)
        {
            sb.AppendLine($"                {invocation};");
            sb.AppendLine("                writer.WriteNullValue();");
        }
        else
        {
            sb.AppendLine($"                var result = {invocation};");
            sb.Append(json.Write(method.ReturnType, "result", "                ", location));
        }

        sb.AppendLine("                return true;");
        sb.AppendLine("            }");
        return sb.ToString();
    }

    private static string? Injected(ITypeSymbol type) => type.ToDisplayString() switch
    {
        "PKHeX.Facade.Game" => "session.RequireGame()",
        "PKHeX.Everywhere.Engine.Session" => "session",
        _ => null,
    };
}
